#!/usr/bin/env python3
"""Generate Exp7Lean/ClassGroup/KnownData.lean.

For each prime q in `known` (class group of Q(sqrt(-q)) of exponent 7) and each l = 2..floor(sqrt q)
emit a certificate:
  .comp a      l is composite, a | l, 1 < a < l
  .inert       X^2 - X + (q+1)/4 has no root mod l
  .split x y   4 l^7 = x^2 + q y^2, l does not divide y
plus a non-principality witness: the least split prime l with 4 l < q and s with
l | s (s+1) + (q+1)/4 (so t = s + 1 is a root).  For the class-number-one primes the same with
exponent 1 (4 l = x^2 + q y^2) and no witness.

Everything emitted is re-checked by the Lean kernel; this script is not trusted.

Usage: python3 gen_known_data.py > KnownData.lean
"""
import math
import sys

import numpy as np
from sympy import isprime

KNOWN = [71, 151, 223, 251, 463, 467, 487, 587, 811, 827, 859, 1163, 1171, 1483,
         1523, 1627, 1787, 1987, 2011, 2083, 2179, 2251, 2467, 2707, 3019, 3067, 3187, 3907, 4603,
         5107, 5923, 63499, 118843]
CLASS_ONE = [3, 7, 11, 19, 43, 67, 163]


def roots(q, l):
    A = (q + 1) // 4
    return [r for r in range(l) if (r * r - r + A) % l == 0]


def solve(q, l, n):
    """Least y >= 1 with l not dividing y and 4 l^n - q y^2 a square; returns (x, y) or None."""
    m = 4 * l ** n
    assert m < 2 ** 62
    ymax = math.isqrt(m // q)
    step = 1 << 20
    for lo in range(1, ymax + 1, step):
        ys = np.arange(lo, min(lo + step, ymax + 1), dtype=np.int64)
        rem = m - q * ys * ys
        xs = np.rint(np.sqrt(rem.astype(np.float64))).astype(np.int64)
        for dx in (-1, 0, 1):
            cand = xs + dx
            hit = np.nonzero((cand >= 0) & (cand * cand == rem) & (ys % l != 0))[0]
            if len(hit):
                y = int(ys[hit[0]])
                x = math.isqrt(m - q * y * y)
                assert x * x + q * y * y == m and y % l != 0
                return x, y
    return None


def certs(q, n):
    out = []
    N = math.isqrt(q)
    for l in range(2, N + 1):
        if not isprime(l):
            a = next(a for a in range(2, l) if l % a == 0)
            out.append(f".comp {a}")
        elif not roots(q, l):
            out.append(".inert")
        else:
            sol = solve(q, l, n)
            if sol is None:
                raise SystemExit(f"q={q} l={l} n={n}: no solution with l not dividing y")
            out.append(f".split {sol[0]} {sol[1]}")
    assert q < (len(out) + 2) ** 2
    return out


def witness(q):
    for l in range(2, q):
        if isprime(l) and 4 * l < q:
            rs = roots(q, l)
            if rs:
                t = rs[0] if rs[0] >= 1 else l
                s = t - 1
                assert (s * (s + 1) + (q + 1) // 4) % l == 0
                return l, s
    raise SystemExit(f"q={q}: no witness")


def fmt_list(items):
    lines, cur = [], "  "
    for i, it in enumerate(items):
        piece = it + (", " if i + 1 < len(items) else "")
        if len(cur) + len(piece) > 98:
            lines.append(cur.rstrip())
            cur = "  "
        cur += piece
    lines.append(cur.rstrip())
    return "[\n" + "\n".join(lines) + "]" if items else "[]"


def main():
    w = sys.stdout.write
    w("import Exp7Lean.ClassGroup.Criterion\n\n")
    w("/-!\nExponent 7: certificates for the 33 known primes and the class-number-one primes.\n\n")
    w("Generated by `gen_known_data.py`; do not edit. Every certificate is checked by the kernel\n")
    w("(`decide +kernel`); no compiled evaluation is trusted.\n-/\n\n")
    w("set_option linter.style.longLine false\n\n")
    w("namespace Exp7\n\nnamespace KnownData\n\n")
    for q in KNOWN:
        assert isprime(q) and q % 4 == 3
        cs = certs(q, 7)
        l, s = witness(q)
        w(f"/-- Certificates for `q = {q}`, `l = 2, …, {len(cs) + 1}` (exponent 7). -/\n")
        w(f"def certs{q} : List Cert := {fmt_list(cs)}\n\n")
        w(f"theorem isExp7_{q} (hq : Nat.Prime {q}) (h4 : {q} % 4 = 3)\n")
        w(f"    (hg : @GenBound {q} ⟨hq⟩ ⟨h4⟩ (Nat.sqrt {q})) : IsExp7 {q} :=\n")
        w(f"  isExp7_of_certs hq h4 hg certs{q} (by decide +kernel) (by decide +kernel)\n")
        w(f"    {l} {s} (by norm_num) (by norm_num) (by decide +kernel)\n\n")
    for q in CLASS_ONE:
        assert isprime(q) and q % 4 == 3
        cs = certs(q, 1)
        w(f"/-- Certificates for `q = {q}`, `l = 2, …, {len(cs) + 1}` (exponent 1). -/\n")
        w(f"def certsOne{q} : List Cert := {fmt_list(cs)}\n\n")
        w(f"theorem not_isExp7_{q} (hq : Nat.Prime {q}) (h4 : {q} % 4 = 3)\n")
        w(f"    (hg : @GenBound {q} ⟨hq⟩ ⟨h4⟩ (Nat.sqrt {q})) : ¬ IsExp7 {q} :=\n")
        w(f"  not_isExp7_of_certs hq h4 hg certsOne{q} (by decide +kernel) (by decide +kernel)\n\n")
    w("end KnownData\n\nend Exp7\n")


if __name__ == "__main__":
    main()
