"""Generate the Lean data files for the 26 threshold ("robust") certificate rows.

Reads sieve-reduction/robust26.txt (one row per line: T X Q, 32 integers = the first half of the
kernel vector, the full vector being v[63-i] = -v[i]; the last field is ignored) and writes

    Exp7Lean/Cond/Data/Robust{k}.lean   (CHUNK rows per file)
    Exp7Lean/Cond/RobustRows.lean       (the list `robustRows` and `robustRows_ok`)

Each row is one theorem `robustOK_of_check (v := …) (pack := …) (by decide +kernel)`; `pack` is
the table of autocorrelation numerators (base 2^64, offset 2^62), verified against `v` in the
kernel.  Nothing computed here is trusted.

Usage (from the workspace root):  python3 Exp7Lean/Cond/gen_robust.py
"""
import os

SRC = "sieve-reduction/robust26.txt"
OFF = 2**62
B = 2**64
CHUNK = 9
OUT = "Exp7Lean/Cond"


def pack_of(v):
    m = len(v)
    assert m == 64
    cn = [sum(v[k]*v[k+j] for k in range(m-j)) for j in range(m+1)]
    assert all(abs(c) < OFF for c in cn) and cn[0] > 0
    return sum((cn[j] + OFF) * B**j for j in range(m+1))


def read_rows():
    rows = []
    for line in open(SRC):
        t = line.split()
        if not t:
            continue
        assert len(t) == 36
        T, X, Q = int(t[0]), int(t[1]), int(t[2])
        half = [int(z) for z in t[3:35]]
        v = half + [-z for z in reversed(half)]
        rows.append((T, Q, X, v))
    return rows


def row_theorem(T, Q, X, v):
    vs = ", ".join(str(t) for t in v)
    return ("set_option maxRecDepth 100000 in\n"
            "theorem robust_%d : RobustOK %d %d %d :=\n"
            "  robustOK_of_check (v := [%s])\n"
            "    (pack := %d) (by decide +kernel)\n" % (T, T, Q, X, vs, pack_of(v)))


def main():
    rows = read_rows()
    assert len(rows) == 26
    assert [r[0] for r in rows] == sorted(set(r[0] for r in rows))
    os.makedirs(os.path.join(OUT, "Data"), exist_ok=True)
    mods = []
    for c in range(0, len(rows), CHUNK):
        k = c // CHUNK
        chunk = rows[c:c + CHUNK]
        body = ["import Exp7Lean.Cond.RobustCheck", "",
                "/-! Threshold certificate rows T = %d … %d (generated by "
                "`Exp7Lean/Cond/gen_robust.py`). -/" % (chunk[0][0], chunk[-1][0]), "",
                "set_option linter.style.longLine false", "",
                "namespace Exp7", ""]
        for (T, Q, X, v) in chunk:
            body.append(row_theorem(T, Q, X, v))
        body.append("end Exp7")
        open(os.path.join(OUT, "Data", "Robust%d.lean" % k), "w").write("\n".join(body) + "\n")
        mods.append("Robust%d" % k)

    m = ["import Exp7Lean.Cond.Data.%s" % f for f in mods]
    m += ["",
          "/-!",
          "The 26 threshold certificate rows `(T, Q, X)` of `sieve-reduction/robust26.txt`, with their",
          "margins proved in the kernel (generated by `Exp7Lean/Cond/gen_robust.py`).",
          "-/", "",
          "set_option linter.style.longLine false", "",
          "namespace Exp7", "",
          "/-- A threshold certificate row: if no prime below `T` splits in `ℚ(√-q)` and `q > X`,",
          "then `q > Q` (under GRH). -/",
          "structure RRow where",
          "  T : ℕ",
          "  Q : ℕ",
          "  X : ℕ", "",
          "/-- The 26 threshold rows, by increasing `T`. -/",
          "def robustRows : List RRow := ["]
    m += [",\n".join("  ⟨%d, %d, %d⟩" % (T, Q, X) for (T, Q, X, v) in rows) + "]", "",
          "/-- All 26 rows have a kernel vector with positive margin. -/",
          "theorem robustRows_ok : ∀ r ∈ robustRows, RobustOK r.T r.Q r.X := by",
          "  intro r hr",
          "  simp only [robustRows, List.mem_cons, List.not_mem_nil, or_false] at hr",
          "  rcases hr with " + " | ".join(["rfl"] * len(rows))]
    m += ["  · exact robust_%d" % T for (T, Q, X, v) in rows]
    m += ["", "end Exp7", "", "#print axioms Exp7.robustRows_ok"]
    open(os.path.join(OUT, "RobustRows.lean"), "w").write("\n".join(m) + "\n")
    print("wrote", mods)


if __name__ == "__main__":
    main()
