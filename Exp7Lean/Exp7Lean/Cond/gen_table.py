"""Generate Exp7Lean/Cond/Table.lean: the certified table of log p, sqrt p for the primes
below 8400.  The entries below 6400 are copied from Exp7Lean/Numerics/PrimeTable.lean; the new
entries (values of `logLo P20 p`, `sqrtLo20 p`, computed by the Lean kernel) are read from the
file given as argument, one `p L S` per line.  Every entry is re-checked in the kernel by
`primeTable8400_check`, so this script is not trusted.

Usage (from the workspace root):  python3 Exp7Lean/Cond/gen_table.py new_entries.txt
"""
import re, sys

B = 8400
old = [(int(a), int(b), int(c)) for a, b, c in
       re.findall(r"\((\d+), (\d+), (\d+)\)", open("Exp7Lean/Numerics/PrimeTable.lean").read())]
assert len(old) == 834
new = []
for line in open(sys.argv[1]):
    t = re.findall(r"\d+", line.split("info:")[-1])
    if len(t) == 3:
        new.append(tuple(int(x) for x in t))
tab = {p: (L, S) for p, L, S in old}
for p, L, S in new:
    if p in tab:
        assert tab[p] == (L, S)
    tab[p] = (L, S)
primes = [n for n in range(2, B) if all(n % d for d in range(2, int(n**0.5) + 1))]
assert sorted(tab) == primes, (len(tab), len(primes))
rows = ",\n".join("  (%d, %d, %d)" % (p, tab[p][0], tab[p][1]) for p in reversed(primes))

src = r'''import Exp7Lean.Numerics.BenchTable

/-!
# A certified table of `log p` and `√p` for the primes below 8400

`primeTable8400` extends `primeTable6400` (`Numerics/PrimeTable.lean`): a literal list of triples
`(p, L, S)`, one for each of the NPR primes `p < 8400` (decreasing), with

    L ≤ 10^20 · log p ≤ L + 16,        S ≤ 10^20 · √p ≤ S + 1.

The first components are compared with the list computed by trial division
(`primeTable8400_primes`), and every entry with the verified evaluators, including the widths of
the enclosures (`primeTable8400_check`); both are kernel computations.
Generated by `Exp7Lean/Cond/gen_table.py`.
-/

namespace Exp7.Num

open Real

set_option maxRecDepth 100000 in
/-- The primes `p < 8400` with `L = logLo P20 p` and `S = sqrtLo20 p`, in decreasing order. -/
def primeTable8400 : List (ℕ × ℕ × ℕ) := [
ROWS]

set_option maxRecDepth 100000 in
/-- The first components are exactly the primes below `8400` (trial division). -/
theorem primeTable8400_primes : primeTable8400.map Prod.fst = primesBelow 8400 := by
  decide +kernel

set_option maxRecDepth 100000 in
/-- Kernel computation: every entry agrees with the verified evaluators, and the enclosures have
widths at most `16` (logarithm) and `1` (square root). -/
theorem primeTable8400_check :
    listAll (fun e => Nat.beq e.2.1 (logLo P20 e.1) && (Nat.beq e.2.2 (sqrtLo20 e.1) &&
        (Nat.ble (logHi P20 e.1) (Nat.add e.2.1 16) &&
          Nat.ble (sqrtHi20 e.1) (Nat.succ e.2.2))))
      primeTable8400 = true := by
  decide +kernel

theorem mem_primeTable8400_fst (p : ℕ) :
    p ∈ primeTable8400.map Prod.fst ↔ p.Prime ∧ p < 8400 := by
  rw [primeTable8400_primes]; exact mem_primesBelow

/-- Every table entry is a prime below `8400` together with enclosures of `log p` and `√p`
(scale `10^20`, widths `16` and `1`). -/
theorem primeTable8400_spec {p L S : ℕ} (h : (p, L, S) ∈ primeTable8400) :
    p.Prime ∧ p < 8400 ∧
      (L : ℝ) ≤ 10 ^ 20 * log p ∧ 10 ^ 20 * log p ≤ (L : ℝ) + 16 ∧
      (S : ℝ) ≤ 10 ^ 20 * √(p : ℝ) ∧ 10 ^ 20 * √(p : ℝ) ≤ (S : ℝ) + 1 := by
  obtain ⟨hprime, hlt⟩ := (mem_primeTable8400_fst p).mp (List.mem_map.mpr ⟨(p, L, S), h, rfl⟩)
  have hc := (listAll_iff _ _).mp primeTable8400_check (p, L, S) h
  simp only [Bool.and_eq_true] at hc
  obtain ⟨c1, c2, c3, c4⟩ := hc
  have hL : L = logLo P20 p := Nat.eq_of_beq_eq_true c1
  have hS : S = sqrtLo20 p := Nat.eq_of_beq_eq_true c2
  have hLw : logHi P20 p ≤ L + 16 := Nat.le_of_ble_eq_true c3
  have hSw : sqrtHi20 p ≤ S + 1 := Nat.le_of_ble_eq_true c4
  have h1 := logLo_le P20_valid (n := p) hprime.one_lt.le
  have h2 := le_logHi P20_valid (n := p) hprime.one_lt.le
  have hD : ((P20.D : ℕ) : ℝ) = 10 ^ 20 := by norm_num [P20]
  rw [hD] at h1 h2
  have h3 := sqrtLo_le 100000000000000000000 4 7 p
  have h4 := le_sqrtHi 100000000000000000000 4 7 p
  have hD' : ((100000000000000000000 : ℕ) : ℝ) = 10 ^ 20 := by norm_num
  rw [hD'] at h3 h4
  have hLw' : (logHi P20 p : ℝ) ≤ (L : ℝ) + 16 := by exact_mod_cast hLw
  have hSw' : (sqrtHi20 p : ℝ) ≤ (S : ℝ) + 1 := by exact_mod_cast hSw
  refine ⟨hprime, hlt, ?_, ?_, ?_, ?_⟩
  · rw [hL]; exact h1
  · exact h2.trans hLw'
  · rw [hS]; exact h3
  · exact h4.trans hSw'

/-- Completeness: every prime below `8400` has an entry. -/
theorem primeTable8400_complete {p : ℕ} (hp : p.Prime) (hlt : p < 8400) :
    ∃ L S, (p, L, S) ∈ primeTable8400 := by
  have h : p ∈ primeTable8400.map Prod.fst := (mem_primeTable8400_fst p).mpr ⟨hp, hlt⟩
  obtain ⟨⟨q, L, S⟩, hmem, hq⟩ := List.mem_map.mp h
  simp only at hq
  subst hq
  exact ⟨L, S, hmem⟩

theorem primeTable8400_nodup : (primeTable8400.map Prod.fst).Nodup := by
  rw [primeTable8400_primes]; exact primesBelow_nodup 8400

/-- The entries below `X ≤ 8400` are the primes below `X`. -/
theorem primeTable8400_filter {X : ℕ} (hX : X ≤ 8400) :
    (primeTable8400.map Prod.fst).toFinset.filter (· < X) =
      (Finset.range X).filter Nat.Prime :=
  toFinset_filter_lt (B := 8400) mem_primeTable8400_fst hX

end Exp7.Num

#print axioms Exp7.Num.primeTable8400_spec
#print axioms Exp7.Num.primeTable8400_complete
#print axioms Exp7.Num.primeTable8400_filter
'''
src = src.replace("NPR", str(len(primes))).replace("ROWS", rows)
open("Exp7Lean/Cond/Table.lean", "w").write(src)
print("wrote Exp7Lean/Cond/Table.lean with", len(primes), "entries")
