"""Generate the Lean data files for the 175 certificate rows.

Reads lowrange/certificate_full.json, matches the rows with `allRows` (Exp7Lean/Basic.lean) and
`lowRows` (Exp7Lean/Low.lean) by (Q, X), and writes

    Exp7Lean/Rows/Data/High{k}.lean   (rows of allRows, CHUNK per file)
    Exp7Lean/Rows/Data/Low{k}.lean    (rows of lowRows, CHUNK per file)
    Exp7Lean/Rows/Margins.lean        (the two target theorems)

Each row is one theorem `rowOK_of_check (v := …) (pack := …) (by decide +kernel)`; `pack` is the
table of autocorrelation numerators (base 2^64, offset 2^62), verified against `v` in the kernel.

Usage (from the workspace root):  python3 Exp7Lean/Rows/gen_rows.py
"""
import json, os, re, sys

CERT = "/home/zlab/GitHub/exponent-seven/lowrange/certificate_full.json"
OFF = 2**62
B = 2**64
CHUNK = 15
OUT = "Exp7Lean/Rows"


def pack_of(v):
    m = len(v)
    assert m == 64
    cn = [sum(v[k]*v[k+j] for k in range(m-j)) for j in range(m+1)]
    assert all(abs(c) < OFF for c in cn) and cn[0] > 0
    return sum((cn[j] + OFF) * B**j for j in range(m+1))


def lean_rows(path, name):
    src = open(path).read()
    i = src.index("def %s : List Row := [" % name)
    j = src.index("]", i)
    return [(int(a), int(b)) for a, b in re.findall(r"⟨(\d+), (\d+)⟩", src[i:j])]


def lean_list(name, src):
    return lean_rows(src, name)


def row_theorem(thm, Q, X, v, pack):
    vs = ", ".join(str(t) for t in v)
    return ("set_option maxRecDepth 100000 in\n"
            "theorem %s : RowOK ⟨%d, %d⟩ :=\n"
            "  rowOK_of_check (v := [%s])\n"
            "    (pack := %d) (by decide +kernel)\n" % (thm, Q, X, vs, pack))


def write_chunks(prefix, tag, rows, data):
    files = []
    for c in range(0, len(rows), CHUNK):
        k = c // CHUNK
        mod = "%s%d" % (prefix, k)
        body = ["import Exp7Lean.Rows.Check", "",
                "/-! Certificate rows %s %d–%d (generated by `Exp7Lean/Rows/gen_rows.py`). -/" %
                (tag, c, min(c + CHUNK, len(rows)) - 1), "",
                "set_option linter.style.longLine false", "",
                "namespace Exp7.Rows", ""]
        for idx in range(c, min(c + CHUNK, len(rows))):
            Q, X = rows[idx]
            v = data[(Q, X)]
            body.append(row_theorem("%s_%d" % (tag, idx), Q, X, v, pack_of(v)))
        body.append("end Exp7.Rows")
        open(os.path.join(OUT, "Data", mod + ".lean"), "w").write("\n".join(body) + "\n")
        files.append(mod)
    return files


def main():
    c = json.load(open(CERT))
    data = {}
    for r in c["bootstrap"] + c["ladder"]:
        key = (r["Q"], r["X"])
        assert key not in data
        data[key] = r["v"]
    high = lean_rows("Exp7Lean/Basic.lean", "bootstrapRows") + lean_rows("Exp7Lean/Basic.lean", "ladderRows")
    low = lean_rows("Exp7Lean/Low.lean", "lowRows")
    assert len(high) == 51 and len(low) == 124 and len(data) == 175
    assert set(high) | set(low) == set(data)
    os.makedirs(os.path.join(OUT, "Data"), exist_ok=True)
    fh = write_chunks("High", "high", high, data)
    fl = write_chunks("Low", "low", low, data)

    def chain(tag, n):
        s = ""
        for i in range(n):
            s += "  rowMargins_cons %s_%d <|\n" % (tag, i)
        return s + "  rowMargins_nil\n"

    m = ["import Exp7Lean.Final2"]
    m += ["import Exp7Lean.Rows.Data.%s" % f for f in fh + fl]
    m += ["",
          "/-!",
          "The numerical margins of the 175 certificate rows, proved in the kernel",
          "(generated by `Exp7Lean/Rows/gen_rows.py`).",
          "-/", "",
          "namespace Exp7", "",
          "open Exp7.Rows", "",
          "theorem rowMargins_nil : RowMargins [] := fun _ h => absurd h List.not_mem_nil", "",
          "theorem rowMargins_cons {r : Row} {rs : List Row} (h : RowOK r) (hs : RowMargins rs) :",
          "    RowMargins (r :: rs) := by",
          "  intro r' hr'",
          "  rcases List.mem_cons.mp hr' with rfl | h'",
          "  · exact h",
          "  · exact hs r' h'", "",
          "/-- The numerical margins of the 51 rows of `allRows`. -/",
          "theorem rowMargins_allRows : RowMargins allRows :=",
          chain("high", len(high)),
          "/-- The numerical margins of the 124 rows of `lowRows`. -/",
          "theorem rowMargins_lowRows : RowMargins lowRows :=",
          chain("low", len(low)),
          "end Exp7", "",
          "#print axioms Exp7.rowMargins_allRows",
          "#print axioms Exp7.rowMargins_lowRows"]
    open(os.path.join(OUT, "Margins.lean"), "w").write("\n".join(m) + "\n")
    print("wrote", fh, fl)


if __name__ == "__main__":
    main()
