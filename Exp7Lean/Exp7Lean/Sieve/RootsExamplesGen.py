def ex(S, y, name, brute_check=False, eight=False, note=""):
    c = make_cert(S, y); R = roots_of(S, c); C = lean_cert(c)
    A(f"/-! ### `y = {y}`{note}: {len(R)} roots -/\n")
    A(f"/-- Certificate for `y = {y}`. -/")
    A(f"def {name} : Cert :=\n  {C}\n")
    A(f"example : rootsOk {S} {y} {name} = true := by decide +kernel\n")
    Rs = ", ".join(map(str, R))
    A(f"example : rootsOf {S} {name} =\n    [{Rs}] := by\n  decide +kernel\n")
    A(f"example : rootsSoundB {S} {y} (rootsOf {S} {name}) = true := by decide +kernel\n")
    if brute_check:
        B = brute(S, y)
        assert sorted(R) == B
        A(f"example : brute {S} ({y} * {y}) = [{', '.join(map(str, B))}] := by\n  decide +kernel\n")
        A(f"example : sortL (rootsOf {S} {name}) = brute {S} ({y} * {y}) := by decide +kernel\n")
    if eight:
        R8 = roots_of8(S, y, c)
        if y <= 60: assert sorted(R8) == brute8(S, y)
        A(f"example : rootsOf8 {S} {y} {name} =\n    [{', '.join(map(str, R8))}] := by\n  decide +kernel\n")
    return c, R

