#!/usr/bin/env python3
"""Writes Exp7Lean/Sieve/All.lean: `theorem Exp7.searchHigh : Exp7.SearchHigh` from the 465 files
P<p>.lean (which must have been built: see run_all.sh).  With --test N only the import and the
chain for the first N primes are written (theorem `Done [p_1, …, p_N]`), to test the mechanism."""
import os
import sys
import gen

ps = [p for p in range(701, 4298) if gen.is_prime(p)]
test = None
if '--test' in sys.argv:
    test = int(sys.argv[sys.argv.index('--test') + 1])
    ps = ps[:test]
out = ['/- Generated by Exp7Lean/Sieve/gen_all.py. -/', 'import Exp7Lean.Sieve.Assembly']
out += ['import Exp7Lean.Sieve.P%d' % p for p in ps]
out += ['', 'set_option maxRecDepth 100000', '', 'namespace Exp7.Sieve', '']
if test is None:
    out.append('theorem done_highPrimes : Done highPrimes :=')
else:
    out.append('theorem done_test : Done [%s] :=' % ', '.join(map(str, ps)))
out.append('  done_nil')
for p in reversed(ps):
    out.append('    |>.cons %d Exp7.search_%d' % (p, p))
out.append('')
if test is None:
    out += ['end Exp7.Sieve', '',
            '/-- Completeness of the main search, proved in the kernel. -/',
            'theorem Exp7.searchHigh : Exp7.SearchHigh :=',
            '  Exp7.Sieve.searchHigh_of_done Exp7.Sieve.done_highPrimes', '',
            '#print axioms Exp7.searchHigh', '']
    name = 'All.lean'
else:
    out += ['#print axioms done_test', '', 'end Exp7.Sieve', '']
    name = 'AllTest.lean'
open(os.path.join(gen.HERE, name), 'w').write('\n'.join(out))
