#!/usr/bin/env python3
"""Writes Exp7Lean/SieveLow/All.lean: `theorem Exp7.searchLow : Exp7.SearchLow` from the 401 files
P<p>.lean (which must have been compiled: see run_low.sh).  With `--test p1 p2 ...` only the import
and the chain for the given primes are written (theorem `DoneLow [p1, p2, ...]`, file AllTest.lean),
to test the mechanism."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def is_prime(n):
    return n > 1 and all(n % d for d in range(2, int(n ** 0.5) + 1))


ps = [p for p in range(3, 2760) if is_prime(p)]
test = '--test' in sys.argv
if test:
    ps = [int(s) for s in sys.argv[sys.argv.index('--test') + 1:]]
out = ['/- Generated by Exp7Lean/SieveLow/gen_low_all.py. -/', 'import Exp7Lean.SieveLow.Assembly']
out += ['import Exp7Lean.SieveLow.P%d' % p for p in ps]
out += ['', 'set_option maxRecDepth 100000', '', 'namespace Exp7.SieveLow', '']
if test:
    out.append('theorem done_test : DoneLow [%s] :=' % ', '.join(map(str, ps)))
else:
    out.append('theorem done_lowPrimes : DoneLow lowPrimes :=')
out.append('  doneLow_nil')
for p in reversed(ps):
    out.append('    |>.cons %d Exp7.searchLow_%d' % (p, p))
out.append('')
if test:
    out += ['#print axioms done_test', '', 'end Exp7.SieveLow', '']
    name = 'AllTest.lean'
else:
    out += ['end Exp7.SieveLow', '',
            '/-- Completeness of the low-range search, proved in the kernel. -/',
            'theorem Exp7.searchLow : Exp7.SearchLow :=',
            '  Exp7.SieveLow.searchLow_of_done Exp7.SieveLow.done_lowPrimes', '',
            '#print axioms Exp7.searchLow', '']
    name = 'All.lean'
open(os.path.join(HERE, name), 'w').write('\n'.join(out))
print('wrote', os.path.join(HERE, name))
