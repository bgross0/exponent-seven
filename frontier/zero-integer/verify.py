#!/usr/bin/env python3
"""Independent integer-interval evaluation of the zero-obstruction rows.

Python standard library only. All numerical endpoints are integers divided
by 10**40; every arithmetic operation rounds outward. The prime table is
generated by Eratosthenes. This checks numerical inequalities, not the
analytic argument or a Lean theorem. See README.md for every remainder bound.
"""

from dataclasses import dataclass
from fractions import Fraction
from functools import lru_cache
from math import comb, isqrt
import argparse
import json
import time

SCALE = 10**40
OUTPUT_SCALE = 10**6


def ceildiv(a, b):
    assert b > 0
    return -((-a) // b)


@dataclass(frozen=True, slots=True)
class Interval:
    lo: int
    hi: int

    def __post_init__(self):
        if self.lo > self.hi:
            raise ValueError("reversed interval")

    @staticmethod
    def exact(n):
        if not isinstance(n, int):
            raise TypeError("exact values must be integers")
        return Interval(n * SCALE, n * SCALE)

    @staticmethod
    def rational(n, d=1):
        if d < 0:
            n, d = -n, -d
        if d == 0:
            raise ZeroDivisionError
        return Interval(n * SCALE // d, ceildiv(n * SCALE, d))

    @staticmethod
    def coerce(x):
        return x if isinstance(x, Interval) else Interval.exact(x)

    def __add__(self, other):
        other = self.coerce(other)
        return Interval(self.lo + other.lo, self.hi + other.hi)

    __radd__ = __add__

    def __neg__(self):
        return Interval(-self.hi, -self.lo)

    def __sub__(self, other):
        return self + -self.coerce(other)

    def __rsub__(self, other):
        return self.coerce(other) + -self

    def __mul__(self, other):
        if isinstance(other, int):
            ends = (self.lo * other, self.hi * other)
            return Interval(min(ends), max(ends))
        other = self.coerce(other)
        products = (self.lo * other.lo, self.lo * other.hi,
                    self.hi * other.lo, self.hi * other.hi)
        return Interval(min(products) // SCALE,
                        ceildiv(max(products), SCALE))

    __rmul__ = __mul__

    def __truediv__(self, other):
        if isinstance(other, int):
            if other < 0:
                return -self / -other
            if other == 0:
                raise ZeroDivisionError
            return Interval(self.lo // other, ceildiv(self.hi, other))
        other = self.coerce(other)
        if other.hi < 0:
            return -self / -other
        if other.lo <= 0:
            raise ZeroDivisionError("denominator interval contains zero")
        if self.lo >= 0:
            return Interval(self.lo * SCALE // other.hi,
                            ceildiv(self.hi * SCALE, other.lo))
        if self.hi <= 0:
            return Interval(self.lo * SCALE // other.lo,
                            ceildiv(self.hi * SCALE, other.hi))
        return Interval(self.lo * SCALE // other.lo,
                        ceildiv(self.hi * SCALE, other.lo))

    def __rtruediv__(self, other):
        return self.coerce(other) / self

    def square(self):
        lower = 0 if self.lo <= 0 <= self.hi else min(self.lo**2, self.hi**2)
        return Interval(lower // SCALE,
                        ceildiv(max(self.lo**2, self.hi**2), SCALE))

    def enclosure(self, scale=OUTPUT_SCALE):
        return [self.lo * scale // SCALE, ceildiv(self.hi * scale, SCALE)]


def _log_ratio(n, d):
    """log(n/d), for integers 1 <= n/d <= 2, using 50 atanh terms."""
    assert d > 0 and d <= n <= 2 * d
    if n == d:
        return Interval.exact(0)
    zlo = (n - d) * SCALE // (n + d)
    zhi = ceildiv((n - d) * SCALE, n + d)
    z2lo = zlo * zlo // SCALE
    z2hi = ceildiv(zhi * zhi, SCALE)
    plo, phi = zlo, zhi
    slo = shi = 0
    terms = 50
    for j in range(terms):
        denominator = 2 * j + 1
        slo += plo // denominator
        shi += ceildiv(phi, denominator)
        plo = plo * z2lo // SCALE
        phi = ceildiv(phi * z2hi, SCALE)
    # 2 sum_{j>=m} z^(2j+1)/(2j+1)
    # <= 9 / (4 (2m+1) 3^(2m+1)), since 0 <= z <= 1/3.
    tail = ceildiv(9 * SCALE, 4 * (2 * terms + 1) * 3**(2 * terms + 1))
    return Interval(2 * slo, 2 * shi + tail)


LOG2 = _log_ratio(2, 1)


@lru_cache(maxsize=None)
def log_integer(n):
    if not isinstance(n, int) or n <= 0:
        raise ValueError("log_integer needs a positive integer")
    k = n.bit_length() - 1
    return k * LOG2 + _log_ratio(n, 1 << k)


def logarithm(x):
    x = Interval.coerce(x)
    if x.lo <= 0:
        raise ValueError("logarithm interval must be positive")
    base = log_integer(SCALE)
    return Interval((log_integer(x.lo) - base).lo,
                    (log_integer(x.hi) - base).hi)


def square_root(x):
    x = Interval.coerce(x)
    if x.lo < 0:
        raise ValueError("square root interval must be nonnegative")
    lower = isqrt(x.lo * SCALE)
    upper = isqrt(x.hi * SCALE)
    if upper * upper != x.hi * SCALE:
        upper += 1
    return Interval(lower, upper)


def _exp_endpoint(x):
    """Enclose exp(x/SCALE); x is an integer, possibly negative."""
    if x == 0:
        return Interval.exact(1)
    if x < 0:
        return 1 / _exp_endpoint(-x)
    reduction = 0
    while x > (SCALE << reduction):
        reduction += 1
    denominator = 1 << reduction
    y = Interval(x // denominator, ceildiv(x, denominator))
    assert 0 <= y.lo <= y.hi <= SCALE
    term = result = Interval.exact(1)
    terms = 40
    for k in range(1, terms + 1):
        term = term * y / k
        result = result + term
    next_term = term * y / (terms + 1)
    # For 0 <= y <= 1 the remainder after degree 40 is <= twice
    # the first omitted term: subsequent term ratios are <= 1/42.
    result = Interval(result.lo, result.hi + 2 * next_term.hi)
    for _ in range(reduction):
        result = result.square()
    return result


def exponential(x):
    x = Interval.coerce(x)
    return Interval(_exp_endpoint(x.lo).lo, _exp_endpoint(x.hi).hi)


def sinh(x):
    return (exponential(x) - exponential(-x)) / 2


def cosh(x):
    return (exponential(x) + exponential(-x)) / 2


def atan_reciprocal(q, terms=40):
    """Alternating-series enclosure; all partial sums are exact rationals."""
    assert q >= 2 and terms >= 1
    value = sum((Fraction((-1)**j, (2 * j + 1) * q**(2 * j + 1))
                 for j in range(terms)), Fraction())
    following = value + Fraction((-1)**terms,
                                 (2 * terms + 1) * q**(2 * terms + 1))
    lower, upper = min(value, following), max(value, following)
    return Interval(lower.numerator * SCALE // lower.denominator,
                    ceildiv(upper.numerator * SCALE, upper.denominator))


def harmonic(n):
    assert n >= 0
    return Interval(sum(SCALE // k for k in range(1, n + 1)),
                    sum(ceildiv(SCALE, k) for k in range(1, n + 1)))


def constants():
    pi = 16 * atan_reciprocal(5) - 4 * atan_reciprocal(239)
    # A_n = H_n - log n - 1/(2n) < gamma < A_n + 1/(12n^2).
    # The README derives this enclosure from an elementary telescoping series.
    n = 10000
    base = harmonic(n) - log_integer(n) - Interval.rational(1, 2 * n)
    gamma = Interval(base.lo, (base + Interval.rational(1, 12 * n**2)).hi)
    return pi, gamma


def primes_below(limit):
    if limit <= 2:
        return []
    sieve = bytearray(b"\x01") * limit
    sieve[0] = sieve[1] = 0
    for p in range(2, isqrt(limit - 1) + 1):
        if sieve[p]:
            start = p * p
            count = (limit - 1 - start) // p + 1
            sieve[start:limit:p] = b"\x00" * count
    return [p for p in range(2, limit) if sieve[p]]


# Work in t = u/log X. The five slope jumps of the Haar autocorrelation
# are convolved with a triangular kernel. Integrating the slope jumps
# twice gives the truncated-cube representation below.
AA, BB = Fraction(99, 200), Fraction(1, 200)
NN = 2 * AA - 2 * BB
DIVISOR = 24 * BB * BB * NN
SHIFTS = {}
for coefficient, knot in zip((-1, 4, -6, 4, -1),
                             (-2 * AA, -AA, Fraction(), AA, 2 * AA)):
    for weight, shift in ((1, knot - 2 * BB), (-2, knot), (1, knot + 2 * BB)):
        SHIFTS[shift] = SHIFTS.get(shift, 0) + coefficient * weight
BREAKS = sorted({Fraction(), Fraction(1),
                 *(k for k in SHIFTS if 0 < k < 1)})
PIECES = []
for left, right in zip(BREAKS, BREAKS[1:]):
    cs = [Fraction() for _ in range(4)]
    for knot, coefficient in SHIFTS.items():
        if knot <= left:
            for degree in range(4):
                cs[degree] += (coefficient * comb(3, degree) *
                               (-knot)**(3 - degree) / DIVISOR)
    PIECES.append((left, right, cs,
                   [Interval.rational(c.numerator, c.denominator) for c in cs]))


def f_fraction(t):
    """Exact truncated-power reference, used to test the polynomial compiler."""
    return sum((c * max(t - k, Fraction())**3 for k, c in SHIFTS.items()),
               Fraction()) / DIVISOR


def test_function(t):
    values = []
    for left, right, _, coefficients in PIECES:
        if t.hi * left.denominator < left.numerator * SCALE:
            continue
        if t.lo * right.denominator > right.numerator * SCALE:
            continue
        value = Interval.exact(0)
        for c in reversed(coefficients):
            value = value * t + c
        values.append(value)
    # Support is [0,1] on the half-line; including zero when an enclosure
    # overlaps the right endpoint handles endpoint rounding conservatively.
    if t.lo <= SCALE <= t.hi or t.lo > SCALE:
        values.append(Interval.exact(0))
    if not values:
        raise ValueError("test-function argument outside nonnegative support")
    return Interval(min(v.lo for v in values), max(v.hi for v in values))


ROWS = [(19000, 39 * 10**29, 10**32),
        (30000, 10**32, 10**40),
        (100000, 10**40, 10**60),
        (1000000, 10**60, 10**162)]


def check_row(X, Qmin, Qmax, pi, gamma, primes):
    started = time.monotonic()
    if not 4 * X**7 < Qmin <= Qmax:
        raise ValueError("row does not satisfy 4*X**7 < Qmin <= Qmax")
    L, logq = log_integer(X), log_integer(Qmax)
    a, b = L * 99 / 200, L / 200
    N = 2 * a - 2 * b
    if (a - 2 * b).lo <= 0:
        raise ArithmeticError("the smoothing parameters do not satisfy 2b<a")
    P = Interval.exact(0)
    count = 0
    for p in primes:
        if p >= X:
            break
        lp = log_integer(p)
        n, k, sign = p, 1, -1
        while n < X:
            f = test_function((lp * k) / L)
            P = P + (lp * (2 * sign)) * f / square_root(n)
            count += 1
            n, k, sign = n * p, k + 1, -sign
    J = 14 / (3 * N)
    logpi = logarithm(pi)
    constant = logpi + gamma - pi / 2 + 3 * LOG2
    margin = P - J + constant - logq
    d = Interval.rational(1, 100)
    s, c = sinh(d * L / 2), cosh(d * L / 2)
    A = (2 * a * s).square() / N
    B = (4 * s + 2 * a * d * c).square() / N
    C = 4 * (1 + cosh(a / 2)).square() * cosh(b / 2).square() / (N * b.square())
    Z = logq + 4
    low = (A + B) * Z
    # The sharper profile uses the exact L1 norm and variation of
    # g(u)*sinh(eta*u); see ../zero-audit/AUDIT.md, sections 5 and 7.
    kappa = 3 - gamma - LOG2 / 2 - logpi
    if kappa.hi >= SCALE:
        raise ArithmeticError("the improved zero-mass constant is not below 1")
    taper = sinh(d * (a - b)) - 2 * b * d * cosh(d * (a - b))
    if taper.lo <= 0:
        raise ArithmeticError("the sharper low-zero taper condition failed")
    A_exact = (4 * (cosh(a * d) - 1).square() * sinh(b * d).square()
               / (N * b.square() * d.square().square()))
    B_exact = 16 * sinh(d * (a - b)).square() / N
    low_exact = (A_exact + B_exact) * (logq + 1)
    profiles = []
    for method, T in (("original_s_equals_2", 1000),
                      ("shifted_s_equals_T_plus_1", 100),
                      ("shifted_tail_and_exact_Haar_low_loss", 60)):
        if method == "original_s_equals_2":
            mass = Z
            high = C * (1 + T*T) / T**4 * mass
        else:
            assert T >= 2 and T % 2 == 0
            mass = (logq - logpi + harmonic(T // 2) - gamma + 4) / (2 * T)
            high = C * ((T + 1)**2 + T*T) / T**4 * mass
        chosen_low = low_exact if T == 60 else low
        residual = margin - chosen_low - high
        if residual.lo <= 0:
            raise ArithmeticError(f"nonpositive residual for X={X}, {method}: {residual}")
        profiles.append({"method": method, "height": T,
                         "weighted_mass_upper_enclosure": mass.enclosure(),
                         "low_zero_loss_upper_enclosure": chosen_low.enclosure(),
                         "high_zero_loss_upper_enclosure": high.enclosure(),
                         "residual": residual.enclosure()})
    return {"X": X, "Qmin": str(Qmin), "Qmax": str(Qmax),
            "prime_power_terms": count, "delta": "1/100",
            "output_scale": OUTPUT_SCALE,
            "prime_sum": P.enclosure(), "J_upper_enclosure": J.enclosure(),
            "margin": margin.enclosure(),
            "low_zero_loss_upper_enclosure": low.enclosure(),
            "sharper_profile_preconditions": {
                "kappa_upper_enclosure": kappa.enclosure(),
                "taper_condition_margin": taper.enclosure()},
            "profiles": profiles,
            "elapsed_seconds": round(time.monotonic() - started, 3)}


def endpoint_decimal(n):
    sign = "-" if n < 0 else ""
    whole, fraction = divmod(abs(n), SCALE)
    return f"{sign}{whole}.{fraction:040d}"


def run(rows):
    start = time.monotonic()
    pi, gamma = constants()
    primes = primes_below(max(row[0] for row in rows))
    for a, b in zip(rows, rows[1:]):
        if a[2] != b[1]:
            raise ValueError("rows do not meet")
    results = [check_row(*row, pi, gamma, primes) for row in rows]
    return {"status": "all numerical interval inequalities positive; not a Lean proof",
            "arithmetic": "integer endpoints / 10**40, outward rounding; Python stdlib only",
            "pi_enclosure": [endpoint_decimal(pi.lo), endpoint_decimal(pi.hi)],
            "gamma_enclosure": [endpoint_decimal(gamma.lo), endpoint_decimal(gamma.hi)],
            "rows": results,
            "total_elapsed_seconds": round(time.monotonic() - start, 3)}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("row", nargs="*", type=int, metavar="INTEGER",
                        help="optional X Qmin Qmax; omit for all four rows")
    args = parser.parse_args()
    if len(args.row) not in (0, 3):
        parser.error("supply either no row arguments or X Qmin Qmax")
    rows = [tuple(args.row)] if args.row else ROWS
    print(json.dumps(run(rows), indent=2))
