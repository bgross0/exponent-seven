#!/usr/bin/env python3
"""Generate exact Lean congruence witnesses for the E433 candidate CM polynomials.

The existing rigorous FLINT/Arb reconstruction proposes full integer
coefficients; Lean checks subsequent reductions and all finite congruences.
This script does not constitute a formal CM identification or Hensel theorem.
"""
from __future__ import annotations
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

FORMAL = Path(__file__).resolve().parents[1]
SOURCE = FORMAL.parent / "bsd-localization" / "second_theta"


def lean_list(values):
    def item(x):
        if isinstance(x, (list, tuple)):
            return "(" + ", ".join(map(str, x)) + ")"
        return str(x)
    return "[\n    " + ",\n    ".join(map(item, values)) + "\n  ]"


def generate():
    spec = importlib.util.spec_from_file_location("theta_verifier", SOURCE / "verify_theta.py")
    verifier = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(verifier)
    certificate_bytes = (SOURCE / "certificate.json").read_bytes()
    certificate = json.loads(certificate_bytes)
    if hashlib.sha256(certificate_bytes).hexdigest() != "5e533e6f0ea31a2c59293448a5f2f8077de512b9e3c50e7420f6eafd2a699898":
        raise ValueError("The input certificate has changed; review before regeneration")
    text = '''import BSDFiniteWitness

/-!
# Exact strong-Hensel numerical premises for the E433 candidate polynomials

All polynomial coefficients are supplied as full integers. The displayed
compact reductions and formal derivatives are checked against those full
lists by Lean kernel reduction. For all 147 supplied root approximations,
the kernel verifies residual valuation 24 modulo 433^25, the stated exact
derivative valuation below 25, and the inequalities 24 > 2*s and 24-s >= 4.
The approximations reduce to the canonical roots modulo 433^4.

These numerical premises do not apply a Hensel root-existence theorem in an
extension field. Identifying these candidate polynomials with
the analytic CM/Hilbert class polynomials remains a separate formalization
obligation. The reconstruction script uses rigorous FLINT/Arb, outside Lean.

Generated by scripts/generate_hensel_witness.py from certificate SHA-256
5e533e6f0ea31a2c59293448a5f2f8077de512b9e3c50e7420f6eafd2a699898.
-/

namespace BSDHenselWitness

open BSDFiniteWitness

set_option maxRecDepth 20000
set_option maxHeartbeats 0

/-- The exponent 25 detects both divisibility by 433^24 and failure at 433^25. -/
def modulus : ℕ := 433 ^ 25

/-- Coordinate reduction of an integer coefficient polynomial, low to high. -/
def integerCoefficientsMod (cs : List ℤ) : List Pair :=
  cs.map fun c => ((c % (modulus : ℤ)).toNat, 0)

/-- Formal polynomial differentiation on a coefficient list. -/
def formalDerivative (cs : List ℤ) : List ℤ :=
  (cs.zipIdx.drop 1).map fun ci => (ci.2 : ℤ) * ci.1

/-- The exact finite divisibility tests, stated as propositions. For a pair
`(a,b)`, divisibility means divisibility of both coordinates. -/
def numericalPremises (cs dcs : List Pair) (root : Pair) (s : ℕ) : Prop :=
  let v := evaluateMod modulus cs root
  let dv := evaluateMod modulus dcs root
  v.1 % (433 ^ 24) = 0 ∧ v.2 % (433 ^ 24) = 0 ∧ v ≠ (0, 0) ∧
  dv.1 % (433 ^ s) = 0 ∧ dv.2 % (433 ^ s) = 0 ∧
  (dv.1 % (433 ^ (s + 1)), dv.2 % (433 ^ (s + 1))) ≠ (0, 0) ∧
  2 * s < 24 ∧ 4 ≤ 24 - s

instance (cs dcs : List Pair) (root : Pair) (s : ℕ) :
    Decidable (numericalPremises cs dcs root s) := by
  unfold numericalPremises
  infer_instance

'''
    for cm in certificate["CM"]:
        D = cm["discriminant"]
        tag = "71" if D == -71 else "44375"
        cs = verifier.class_polynomial(D)
        if verifier.hash_coefficients(cs) != cm["class_polynomial_sha256"]:
            raise ValueError("Candidate polynomial hash mismatch")
        ds = [i * cs[i] for i in range(1, len(cs))]
        M = 433**25
        roots = cm["root_lifts"]
        vals = [s for h, s in cm["hensel_valuations"]]
        if any(h != 24 for h, _ in cm["hensel_valuations"]):
            raise ValueError("Unexpected residual valuation")
        text += f"-- Candidate coefficient hash: {cm['class_polynomial_sha256']}\n"
        for name, typ, values in [
            (f"candidate{tag}Coefficients", "List ℤ", cs),
            (f"candidate{tag}Mod25", "List Pair", [(c % M, 0) for c in cs]),
            (f"derivative{tag}Mod25", "List Pair", [(c % M, 0) for c in ds]),
            (f"rootLifts{tag}", "List Pair", roots),
            (f"derivativeValuations{tag}", "List ℕ", vals),
        ]:
            text += f"\ndef {name} : {typ} :=\n  {lean_list(values)}\n"
        canonical = "cm71Roots433" if tag == "71" else "cm433Roots"
        n = len(roots)
        text += f'''
/-- Full integer coefficients have the claimed degree and monic leading entry. -/
theorem candidate{tag}_degree_data :
    candidate{tag}Coefficients.length = {n + 1} ∧
    candidate{tag}Coefficients.getLast? = some 1 := by
  decide +kernel

/-- Bind the compact residues to EVERY full integer coefficient. -/
theorem candidate{tag}_reduction :
    integerCoefficientsMod candidate{tag}Coefficients = candidate{tag}Mod25 := by
  decide +kernel

/-- Bind derivative residues to the formal derivative of the full polynomial. -/
theorem derivative{tag}_reduction :
    integerCoefficientsMod (formalDerivative candidate{tag}Coefficients) =
      derivative{tag}Mod25 := by
  decide +kernel

/-- Every high-precision approximation reduces to its previously checked root ball. -/
theorem rootLifts{tag}_binding :
    rootLifts{tag}.length = {n} ∧ derivativeValuations{tag}.length = {n} ∧
    rootLifts{tag}.map (fun x => (x.1 % (433^4), x.2 % (433^4))) = {canonical} := by
  decide +kernel

/-- All supplied approximations satisfy the exact strong-Hensel numerical premises. -/
theorem rootLifts{tag}_numerical : ∀ i : Fin {n},
    numericalPremises (integerCoefficientsMod candidate{tag}Coefficients)
      (integerCoefficientsMod (formalDerivative candidate{tag}Coefficients))
      rootLifts{tag}[i.val]! derivativeValuations{tag}[i.val]! := by
  rw [candidate{tag}_reduction, derivative{tag}_reduction]
  decide +kernel

'''
    text += "end BSDHenselWitness\n"
    return text


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Compare without writing")
    parser.add_argument("--output", type=Path, default=FORMAL / "BSDHenselWitness.lean")
    args = parser.parse_args()
    text = generate()
    if args.check:
        if args.output.read_text() != text:
            raise SystemExit("Generated Lean source differs")
        print("HENSEL_WITNESS_SOURCE_MATCH")
    else:
        args.output.write_text(text)
        print(args.output)
    print("source_sha256", hashlib.sha256(text.encode()).hexdigest())


if __name__ == "__main__":
    main()
